export const ALL_SEO = { ...PAGE_SEO, ...PERSON_SEO };

/* What a page's <title> will actually say, suffix included. */
export function fullTitle(path) {
  const entry = ALL_SEO[path];
  return entry ? entry.title + BRAND_SUFFIX : null;
}

