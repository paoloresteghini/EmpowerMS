/* SEO title and meta description copy, one entry per URL.

   WHY THIS FILE EXISTS AT ALL. Every converted page on the install carries
   NO meta description: zero characters, all sixteen of them. The legacy
   Beaver pages beside them (/home/, /team-old/, /donate-old/, /learn-more/)
   all have one, 340-410 characters long, obviously auto-generated by All in
   One SEO from the page's own text and reading like it ("Mississippians
   committed to MississippiOur team is led by Mi..."). The difference is not
   a setting, it is the conversion: AIOSEO's auto-generator reads
   post_content, and an Elementor page's post_content is empty, because its
   text lives in _elementor_data. So the very act of converting a page
   silently strips its description. Nothing warns about it, and nothing in
   the conversion pipeline put one back.

   The same mechanism has the opposite effect on the `person` CPT: those
   posts DO have post_content, so every bio has a description, and every one
   of them is 359-416 characters, i.e. more than twice what Google will show.
   They are not missing, they are unusable, which is a different defect with
   the same fix: write one.

   WHO IS IN HERE CHANGED ON 2026-08-21. The sheet went to Empower with
   eighteen bios and came back with five rows emptied: Wil Ervin, Brett
   Kittredge, Steven Randle, Katie Elliott and Christopher Koopman. That
   reads as a staff change rather than an edit, and the rest of the returned
   document agrees with it - Wil Ervin's name was taken out of the Capitol
   Chat description in the same pass, and Kienna Horn now carries the
   Communications title Brett Kittredge held. On Paolo's decision the five
   listings were deleted here and the five posts set to draft on the install,
   so the thirteen below are exactly the thirteen published `person` entries.
   test-elementor.mjs asserts that correspondence against the install rather
   than against this count.

   TARGETS (checked by test-elementor.mjs, not by eye):
     title       45-60 characters INCLUDING the " - Empower Mississippi"
                 suffix, which is 22 of them. Over 60 truncates; under 45
                 wastes the pixel width Google gives us. The band is 45 and
                 not the usually-quoted 50 because of the bios: a title is
                 "<name>, <role>", and a long name (Dr. Kristin Vance
                 Richards) leaves no room for a role without truncating the
                 name, which is the half someone searching actually typed.
     description 140-160 characters, and the first ~110 must stand alone,
                 because that is all a phone shows.

   Every description here is written from the page's OWN signed-off copy, or
   from the person's own bio. Nothing is invented, and no figure appears here
   that does not appear on the page it describes (Empower's no-invented-
   statistics rule applies to a search snippet exactly as it applies to a
   heading). Google rewrites 60-70% of descriptions anyway; the one thing
   that makes a rewrite MORE likely is a description the page does not
   deliver on.

   The key is the path, not the page directory name, because the person CPT
   entries have no page directory and the two are not the same set. */

